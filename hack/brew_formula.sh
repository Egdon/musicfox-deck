#!/usr/bin/env bash
# Prints the Homebrew formula of a release for the Egdon/homebrew-tap
# repository (.github/workflows/homebrew.yaml):
#
#   hack/brew_formula.sh v1.0.0 SHA256SUMS [URL]
#
# URL is where the macOS archives are, by default the release's downloads.
# The formula installs the prebuilt binary: Homebrew does not quarantine what
# a formula downloads, so the unsigned binary runs without a Gatekeeper prompt.

set -euo pipefail

tag=$1
version=${tag#v}
sums=$2
base=${3:-https://github.com/Egdon/musicfox-deck/releases/download/$tag}

# checksum ARCH
checksum() {
	local file=musicfox-deck_${version}_darwin_$1.tar.gz
	awk -v f="$file" '$2 == f || $2 == "*" f { print $1; found = 1 } END { exit !found }' "$sums" ||
		{ echo "$sums has no checksum for $file" >&2; return 1; }
}

arm64=$(checksum arm64)
amd64=$(checksum amd64)

cat <<EOF
# Generated by hack/brew_formula.sh in Egdon/musicfox-deck; do not edit.
class MusicfoxDeck < Formula
  desc "NetEase Cloud Music in the terminal, with a 3D cassette deck"
  homepage "https://github.com/Egdon/musicfox-deck"
  version "${version}"
  license "GPL-3.0-only"

  on_arm do
    url "${base}/musicfox-deck_${version}_darwin_arm64.tar.gz"
    sha256 "${arm64}"
  end
  on_intel do
    url "${base}/musicfox-deck_${version}_darwin_amd64.tar.gz"
    sha256 "${amd64}"
  end

  depends_on :macos

  def install
    bin.install "musicfox"
  end

  test do
    ENV["MUSICFOX_ROOT"] = testpath
    assert_match version.to_s, shell_output("#{bin}/musicfox --version")
  end
end
EOF
